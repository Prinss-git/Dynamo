<#
.SYNOPSIS
    Builds student_event_db.hosted.sql: the schema + demo data for a hosted SQL Server
    (MonsterASP.NET, Azure SQL, ...), generated from student_event_db.sql.

.DESCRIPTION
    Hosted databases are created in the host's control panel, and most hosts reject
    CREATE DATABASE / USE, so those lines are removed. Run the output file while
    connected to the hosted database.

    Seeded passwords are encrypted with TokenAuthentication:SecretKey (PasswordManager:
    AES-128-CBC, key = first 16 bytes of the secret, zero IV). The production site must
    NOT reuse the key committed in appsettings.json, so every seeded password is
    re-encrypted with the production key. The demo passwords themselves stay the same
    (Admin@123, Officer@123, Student@123).

.PARAMETER SecretKey
    The production secret key. Leave it out to generate a new random key (printed once:
    copy it into the host's TokenAuthentication__SecretKey setting).

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File Database\build_hosted_script.ps1
#>
param([string]$SecretKey)

$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$source = Join-Path $here "student_event_db.sql"
$target = Join-Path $here "student_event_db.hosted.sql"
$settings = Join-Path $here "..\ASI.Basecode.WebApp\appsettings.json"

function Protect-Password([string]$password, [string]$key) {
    $aesKey = New-Object byte[] 16
    $keyBytes = [Text.Encoding]::UTF8.GetBytes($key)
    [Array]::Copy($keyBytes, $aesKey, [Math]::Min($keyBytes.Length, 16))
    $aes = [Security.Cryptography.Aes]::Create()
    try {
        $aes.Key = $aesKey
        $aes.IV = New-Object byte[] 16
        $plain = [Text.Encoding]::UTF8.GetBytes($password)
        $cipher = $aes.CreateEncryptor().TransformFinalBlock($plain, 0, $plain.Length)
        return [Convert]::ToBase64String($cipher)
    } finally { $aes.Dispose() }
}

# appsettings.json has comments, which ConvertFrom-Json rejects, so read the key with a pattern.
$match = [Text.RegularExpressions.Regex]::Match((Get-Content $settings -Raw), '"SecretKey"\s*:\s*"([^"]*)"')
if (-not $match.Success) { throw "TokenAuthentication:SecretKey not found in appsettings.json." }
$devKey = $match.Groups[1].Value
if (-not $SecretKey) {
    $bytes = New-Object byte[] 32
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $SecretKey = [Convert]::ToBase64String($bytes)
    Write-Host "Generated production secret key (set it as TokenAuthentication__SecretKey on the host):"
    Write-Host "  $SecretKey" -ForegroundColor Yellow
}
if ($SecretKey -eq $devKey) { throw "Use a production key that differs from the one in appsettings.json." }
if ($SecretKey.Length -lt 32) { throw "The secret key must be at least 32 characters (it also signs the login cookie)." }

$sql = [IO.File]::ReadAllText($source)

# 1. Drop the CREATE DATABASE / USE batches (the host already created the database).
$before = $sql.Length
$sql = [Text.RegularExpressions.Regex]::Replace($sql,
    "IF DB_ID\(N'student_event_db'\) IS NULL\s+CREATE DATABASE student_event_db;\s+GO\s+USE student_event_db;\s+GO\s+", "")
if ($sql.Length -eq $before) { throw "CREATE DATABASE / USE block not found in student_event_db.sql." }

# 2. Re-encrypt every demo password with the production key.
foreach ($password in "Admin@123", "Officer@123", "Student@123") {
    $old = Protect-Password $password $devKey
    $new = Protect-Password $password $SecretKey
    if (-not $sql.Contains("'$old'")) { throw "Seeded password for $password not found; has the dev key changed?" }
    $sql = $sql.Replace("'$old'", "'$new'")
}

$header = @"
-- =====================================================================
--  GENERATED by Database\build_hosted_script.ps1 - do not edit by hand.
--  Hosted SQL Server version of student_event_db.sql:
--    * no CREATE DATABASE / USE: connect to the host's database first, then run this file
--    * demo passwords re-encrypted with the production TokenAuthentication:SecretKey
-- =====================================================================

"@
[IO.File]::WriteAllText($target, $header + $sql, (New-Object Text.UTF8Encoding($false)))
Write-Host "Wrote $target"
